"""Street geometry and vehicle kinematics for the Waterloo corridor.

`waterloo_corridor.json` is generated by tools/waterloo_geometry from GRT's GTFS
feed. The frontend ships an identical copy and a line-for-line port of the
kinematics below (frontend/lib/motion/kinematics.ts), so positions computed here
for each simulated minute match what the browser draws between minutes.

Distances are metres along a segment's path, times are seconds.
"""
import json
import math
from functools import lru_cache
from pathlib import Path

DATA = json.loads((Path(__file__).resolve().parent / "waterloo_corridor.json").read_text())

GRID_M = 2.0           # spacing of the speed-limit grid
BUS_ACCEL = 0.9        # m/s^2, comfortable pull-away
BUS_DECEL = 1.1        # m/s^2, comfortable service braking
BUS_TOP_SPEED = 16.0   # m/s (~58 km/h) usual cruising cap
BUS_RUSH_SPEED = 24.0  # m/s: cap may rise this far on straights to keep schedule
FIT_ITERATIONS = 40
MIN_CRUISE = 2.5       # m/s: slower than this, wait at the curb, then drive

SEGMENTS = {(seg["from"], seg["to"]): seg for seg in DATA["segments"]}
STOPS = DATA["stops"]
SIGNALS = DATA["signals"]


def segment(from_id, to_id):
    return SEGMENTS[(from_id, to_id)]


def _lerp_path(path, s):
    """Lon/lat at distance s along an encoded [lon, lat, cumulative_m] path."""
    if s <= path[0][2]:
        return path[0][0], path[0][1]
    if s >= path[-1][2]:
        return path[-1][0], path[-1][1]
    lo, hi = 0, len(path) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if path[mid][2] <= s:
            lo = mid
        else:
            hi = mid
    a, b = path[lo], path[hi]
    f = (s - a[2]) / (b[2] - a[2]) if b[2] > a[2] else 0.0
    return a[0] + (b[0] - a[0]) * f, a[1] + (b[1] - a[1]) * f


LANE_OFFSET_M = DATA["lane_offset_m"]
CURB_BLEND_M = DATA["curb_blend_m"]
_K = math.cos(math.radians(43.465))
_M_PER_DEG = 111_320.0


def _smoothstep(e0, e1, x):
    if e1 <= e0:
        return 1.0 if x >= e1 else 0.0
    t = min(1.0, max(0.0, (x - e0) / (e1 - e0)))
    return t * t * (3.0 - 2.0 * t)


def lateral_offset(seg, s):
    """Metres right of the street centreline: in lane, easing to the curb at stops."""
    length = seg["length_m"]
    start, end = seg["curb_m"]
    lead = 1.0 - _smoothstep(0.0, CURB_BLEND_M, s)
    tail = _smoothstep(length - CURB_BLEND_M, length, s)
    return LANE_OFFSET_M + (start - LANE_OFFSET_M) * lead + (end - LANE_OFFSET_M) * tail


def position(seg, s):
    """Lon/lat of a bus centre `s` metres along the segment, kept to the right."""
    path = seg["path"]
    lon, lat = _lerp_path(path, s)
    a = _lerp_path(path, s - 3.0)
    b = _lerp_path(path, s + 3.0)
    dx = (b[0] - a[0]) * _M_PER_DEG * _K
    dy = (b[1] - a[1]) * _M_PER_DEG
    norm = math.hypot(dx, dy) or 1.0
    off = lateral_offset(seg, s)
    lon += dy / norm * off / (_M_PER_DEG * _K)
    lat += -dx / norm * off / _M_PER_DEG
    return round(lon, 6), round(lat, 6)


def _limits(length, curves, cap, hold_at):
    n = max(1, math.ceil(length / GRID_M))
    v = [cap] * (n + 1)
    for s, limit in curves:
        i = math.floor(s / GRID_M + 0.5)
        if 0 <= i <= n and limit < v[i]:
            v[i] = limit
    v[0] = 0.0
    v[n] = 0.0
    if hold_at is not None:
        v[min(n, max(0, math.floor(hold_at / GRID_M + 0.5)))] = 0.0
    return v


def _grid_s(i, n, length):
    return length if i == n else i * GRID_M


def _speed_profile(length, curves, cap, hold_at, accel, decel):
    """Fastest speeds at each grid node that respect caps, stops and comfort."""
    v = _limits(length, curves, cap, hold_at)
    n = len(v) - 1
    for i in range(1, n + 1):
        ds = _grid_s(i, n, length) - _grid_s(i - 1, n, length)
        reach = math.sqrt(v[i - 1] * v[i - 1] + 2.0 * accel * ds)
        if reach < v[i]:
            v[i] = reach
    for i in range(n - 1, -1, -1):
        ds = _grid_s(i + 1, n, length) - _grid_s(i, n, length)
        reach = math.sqrt(v[i + 1] * v[i + 1] + 2.0 * decel * ds)
        if reach < v[i]:
            v[i] = reach
    return v


def _run_time(length, v):
    n = len(v) - 1
    total = 0.0
    for i in range(1, n + 1):
        ds = _grid_s(i, n, length) - _grid_s(i - 1, n, length)
        total += 2.0 * ds / (v[i - 1] + v[i])
    return total


class Run:
    """One stop-to-stop trip: distance as a function of time since departure.

    The bus pulls away, follows curve speed limits, optionally waits
    `hold_s` at a signal stop line, and brakes into the next stop. Its top
    speed is fitted so the whole trip takes exactly `duration_s`, which is the
    time the Python simulator allotted to the segment.
    """

    def __init__(self, length, curves, duration_s, hold_at=None, hold_s=0.0,
                 accel=BUS_ACCEL, decel=BUS_DECEL, top_speed=BUS_TOP_SPEED, rush_speed=BUS_RUSH_SPEED):
        self.length = length
        self.hold_s = hold_s if hold_at is not None else 0.0
        moving = max(1.0, duration_s - self.hold_s)
        lo, hi = 0.3, top_speed
        v = _speed_profile(length, curves, hi, hold_at, accel, decel)
        if _run_time(length, v) > moving:
            # Behind schedule at the usual cap: go faster on the straights
            # (corners and braking stay comfortable) before compressing time.
            lo, hi = top_speed, rush_speed
            v = _speed_profile(length, curves, hi, hold_at, accel, decel)
        if _run_time(length, v) < moving:
            for _ in range(FIT_ITERATIONS):
                mid = (lo + hi) / 2.0
                trial = _speed_profile(length, curves, mid, hold_at, accel, decel)
                if _run_time(length, trial) > moving:
                    lo = mid
                else:
                    hi = mid
            v = _speed_profile(length, curves, hi, hold_at, accel, decel)
        # A long allowance for a short hop would mean crawling at walking pace;
        # instead the bus waits at its stop and then drives at a modest speed.
        start_hold = 0.0
        if hi < MIN_CRUISE:
            v = _speed_profile(length, curves, MIN_CRUISE, hold_at, accel, decel)
            start_hold = max(0.0, moving - _run_time(length, v))
            moving -= start_hold
        self.start_hold = start_hold
        # Scale time so the trip ends exactly on schedule (a no-op when the
        # fitted cap already matches; faster than comfortable if the schedule
        # is tighter than the street allows).
        scale = moving / _run_time(length, v)
        n = len(v) - 1
        self.n = n
        self.speed = [x / scale for x in v]
        self.times = [start_hold]
        self.hold_index = None
        self.hold_position = None
        if hold_at is not None:
            self.hold_index = min(n, max(0, math.floor(hold_at / GRID_M + 0.5)))
            self.hold_position = _grid_s(self.hold_index, n, length)
        for i in range(1, n + 1):
            ds = _grid_s(i, n, length) - _grid_s(i - 1, n, length)
            t = self.times[-1] + 2.0 * ds / (self.speed[i - 1] + self.speed[i])
            if self.hold_index is not None and i - 1 == self.hold_index:
                t += self.hold_s
            self.times.append(t)
        self.duration = self.times[-1]

    def distance(self, t):
        """Metres travelled `t` seconds after departure."""
        if t <= self.times[0]:
            return 0.0
        if t >= self.duration:
            return self.length
        lo, hi = 0, self.n
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if self.times[mid] <= t:
                lo = mid
            else:
                hi = mid
        s0 = _grid_s(lo, self.n, self.length)
        s1 = _grid_s(hi, self.n, self.length)
        t0 = self.times[lo]
        if self.hold_index is not None and lo == self.hold_index:
            if t - t0 <= self.hold_s:
                return s0
            t0 += self.hold_s
        v0, v1 = self.speed[lo], self.speed[hi]
        dt = self.times[hi] - t0
        tau = t - t0
        a = (v1 - v0) / dt if dt > 0 else 0.0
        return min(s1, s0 + v0 * tau + 0.5 * a * tau * tau)

    def speed_at(self, t):
        if t <= self.times[0] or t >= self.duration:
            return 0.0
        eps = 0.25
        return max(0.0, (self.distance(t + eps) - self.distance(t - eps)) / (2 * eps))


@lru_cache(maxsize=None)
def free_flow_seconds(from_id, to_id, stop_at_signal=False):
    """Fastest comfortable trip: pull away, corners, braking, at most
    BUS_TOP_SPEED. With stop_at_signal the bus also stops at the stop line
    (the red-signal wait itself is added separately)."""
    seg = segment(from_id, to_id)
    hold_at = seg["signal"]["stop_line_m"] if stop_at_signal else None
    v = _speed_profile(seg["length_m"], tuple(map(tuple, seg["curves"])), BUS_TOP_SPEED, hold_at, BUS_ACCEL, BUS_DECEL)
    return _run_time(seg["length_m"], v)


def free_flow_minutes(from_id, to_id, stop_at_signal=False):
    """Fewest whole minutes of driving the simulator may give a segment: never
    faster than the trip model allows at BUS_TOP_SPEED (~58 km/h)."""
    return max(1, math.ceil(free_flow_seconds(from_id, to_id, stop_at_signal) / 60.0))


CAR_SPACING_M = 7.0  # one queued car: ~4.5 m long plus the gap to the next


def queue_cars(traffic_multiplier):
    """Cars waiting ahead of the bus at a red signal: more in heavier traffic."""
    return max(1, min(4, round(1 + 1.5 * (traffic_multiplier - 0.5))))


BUS_FRONT_M = 5.75   # front bumper ahead of the bus's distance-along reference point


def hold_position(seg, queue=0):
    """Where a bus stops at a red signal: at the stop line, or with its front
    bumper just behind `queue` cars that fill the space up to the line."""
    if not queue:
        return seg["signal"]["stop_line_m"]
    return max(5.0, seg["signal"]["stop_line_m"] - BUS_FRONT_M - queue * CAR_SPACING_M)


@lru_cache(maxsize=256)
def bus_run(from_id, to_id, minutes, hold_minutes=0, queue=0):
    seg = segment(from_id, to_id)
    hold_at = hold_position(seg, queue) if hold_minutes else None
    return Run(seg["length_m"], tuple(map(tuple, seg["curves"])), minutes * 60.0, hold_at, hold_minutes * 60.0)
